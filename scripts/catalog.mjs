#!/usr/bin/env node
// scripts/catalog.mjs
//
// WRITE OR CHECK THE CATALOG OF COSYTE'S LIBRARIES (PF1, ST13, ST14).
//
// The catalog is `packages/script-utils/catalog.json`: one record per library, generated from that
// library's own package.json (name, description, release line, engines, repository, docs and npm
// URLs), with its tier from the hand-kept `catalog/tiers.json`, and one record for Pathways. It ships
// in `@cosyte/script-utils`, so the website, docs, the org profile and the knowledgebase read one
// list, and every library checks its description against it.
//
// Usage:
//   node scripts/catalog.mjs write [--root <dir>]   regenerate catalog.json from each package.json
//   node scripts/catalog.mjs check [--root <dir>]   regenerate in memory and compare with the file
//   node scripts/catalog.mjs check --self           check the file against catalog/tiers.json alone
//
// The libraries are read as sibling checkouts, `<root>/<slug>/package.json`, with `<root>` the
// directory above this repository by default: the umbrella, where every repository is a submodule.
// CI checks out config alone, so CI runs `check --self`, which needs no sibling; `write` and `check`
// run where the umbrella is, and a sibling that cannot be read is a refusal, never a skip.
//
// Exit codes: 0 written, or the catalog agrees; 1 the committed catalog differs from what it should
// be; 2 the script could not run (an unreadable tiers file, catalog or package.json, or a bad
// argument).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { buildCatalog } from "../packages/script-utils/catalog.js";
import { isCliEntrypoint } from "../packages/script-utils/index.js";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TIERS_PATH = join(REPO_ROOT, "catalog", "tiers.json");
export const CATALOG_PATH = join(REPO_ROOT, "packages", "script-utils", "catalog.json");

/** Exit 2: the script could not run. */
class InvocationError extends Error {}

/** The header every generated catalog carries, so nobody edits it by hand. */
const GENERATED = {
  $comment:
    "GENERATED by cosyte/config scripts/catalog.mjs from each package's package.json and " +
    "catalog/tiers.json. Do not edit by hand: change the package.json or the tiers file, then run " +
    "`node scripts/catalog.mjs write` from the umbrella.",
};

function readJson(path, what) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (err) {
    throw new InvocationError(`could not read ${what} (${path}): ${err.message}`);
  }
}

/** Every package the tiers file names, in its order. */
export function tieredPackages(tiers) {
  return [...tiers.standards.map((entry) => entry.package), ...tiers.builtOn, tiers.engine.package];
}

/**
 * Generate the catalog from sibling checkouts under `root`.
 *
 * @param {string} root The directory holding one checkout per repository.
 * @param {Record<string, any>} tiers The parsed tiers file.
 * @param {(tiers: object, manifests: Map<string, object>) => object} buildCatalog
 * @returns {object} The catalog, with its generated header.
 */
export function generate(root, tiers, buildCatalog) {
  const manifests = new Map();
  for (const name of tieredPackages(tiers)) {
    const slug = name.replace(/^@cosyte\//, "");
    manifests.set(name, readJson(join(root, slug, "package.json"), `${name}'s package.json`));
  }
  try {
    return { ...GENERATED, ...buildCatalog(tiers, manifests) };
  } catch (err) {
    throw new InvocationError(err.message);
  }
}

/** The catalog as written to disk: two-space JSON and a final newline, which prettier keeps. */
export function serialize(catalog) {
  return `${JSON.stringify(catalog, null, 2)}\n`;
}

/**
 * Check a committed catalog against the tiers file alone: the packages, their order and tiers, the
 * standard names and Pathways' status, and the shape of every generated field.
 *
 * @returns {string[]} One line per problem.
 */
export function checkSelf(catalog, tiers) {
  const problems = [];
  const libraries = Array.isArray(catalog?.libraries) ? catalog.libraries : [];
  const expected = [
    ...tiers.standards.map((entry) => ({
      name: entry.package,
      tier: "standard",
      standard: entry.standard,
    })),
    ...tiers.builtOn.map((name) => ({ name, tier: "built-on" })),
  ];
  if (libraries.length !== expected.length) {
    problems.push(
      `the catalog lists ${libraries.length} libraries; the tiers file names ${expected.length}.`,
    );
  }
  expected.forEach((want, index) => {
    const got = libraries[index];
    if (got?.name !== want.name) {
      problems.push(
        `library ${index + 1} is ${JSON.stringify(got?.name ?? null)}; the tiers file puts ${want.name} there.`,
      );
      return;
    }
    if (got.tier !== want.tier)
      problems.push(
        `${want.name} is tier ${JSON.stringify(got.tier)}; the tiers file says ${want.tier}.`,
      );
    if (want.standard !== undefined && got.standard !== want.standard) {
      problems.push(
        `${want.name}'s standard is ${JSON.stringify(got.standard)}; the tiers file says ${want.standard}.`,
      );
    }
    if (want.standard === undefined && "standard" in got)
      problems.push(`${want.name} is built on the standards and names none.`);
    problems.push(...shapeProblems(got, true));
  });
  const engine = catalog?.engine;
  if (engine?.name !== tiers.engine.package) {
    problems.push(
      `the engine is ${JSON.stringify(engine?.name ?? null)}; the tiers file says ${tiers.engine.package}.`,
    );
  } else {
    for (const [field, value] of [
      ["tier", "engine"],
      ["displayName", tiers.engine.name],
      ["status", tiers.engine.status],
      ["onNpm", tiers.engine.onNpm],
    ]) {
      if (engine[field] !== value) {
        problems.push(
          `the engine's ${field} is ${JSON.stringify(engine[field])}; the tiers file says ${JSON.stringify(value)}.`,
        );
      }
    }
    problems.push(...shapeProblems(engine, false));
  }
  if (catalog?.$comment !== GENERATED.$comment)
    problems.push("the catalog's generated header is missing or edited.");
  return problems;
}

/** The generated fields every record carries, and the forms they take. */
function shapeProblems(record, onNpm) {
  const problems = [];
  const name = record.name;
  const slug = String(name).replace(/^@cosyte\//, "");
  const want = {
    slug,
    docs: `https://docs.cosyte.com/${slug}`,
  };
  for (const [field, value] of Object.entries(want)) {
    if (record[field] !== value)
      problems.push(`${name}'s ${field} is ${JSON.stringify(record[field])}; expected ${value}.`);
  }
  if (typeof record.description !== "string" || record.description.trim() === "")
    problems.push(`${name} has no description.`);
  if (typeof record.line !== "string" || !/^(0\.\d+|[1-9]\d*)$/.test(record.line))
    problems.push(`${name}'s release line ${JSON.stringify(record.line)} is not one.`);
  if (typeof record.engines?.node !== "string") problems.push(`${name} has no engines.node.`);
  if (
    typeof record.repository !== "string" ||
    !/^https:\/\/github\.com\/cosyte\/[A-Za-z0-9._-]+$/.test(record.repository)
  ) {
    problems.push(
      `${name}'s repository ${JSON.stringify(record.repository)} is not a github.com/cosyte URL.`,
    );
  }
  if (onNpm && record.npm !== `https://www.npmjs.com/package/${name}`)
    problems.push(`${name}'s npm URL is ${JSON.stringify(record.npm)}.`);
  return problems;
}

/** Field-level differences between two catalogs, one line each. */
export function diffCatalogs(committed, generated) {
  const lines = [];
  const walk = (a, b, path) => {
    if (JSON.stringify(a) === JSON.stringify(b)) return;
    if (
      a &&
      b &&
      typeof a === "object" &&
      typeof b === "object" &&
      !Array.isArray(a) === !Array.isArray(b)
    ) {
      for (const key of new Set([...Object.keys(a), ...Object.keys(b)]))
        walk(a[key], b[key], `${path}.${key}`);
      return;
    }
    lines.push(`${path}: committed ${JSON.stringify(a)}, package.json says ${JSON.stringify(b)}`);
  };
  walk(committed, generated, "catalog");
  return lines;
}

function parseArgs(argv) {
  const args = argv.filter((arg) => arg !== "--");
  const [mode, ...rest] = args;
  if (mode !== "write" && mode !== "check") {
    throw new InvocationError(
      `the first argument must be write or check, not ${JSON.stringify(mode ?? null)}.`,
    );
  }
  let root = join(REPO_ROOT, "..");
  let self = false;
  for (let i = 0; i < rest.length; i += 1) {
    if (rest[i] === "--root" && typeof rest[i + 1] === "string") {
      root = resolve(rest[i + 1]);
      i += 1;
    } else if (rest[i] === "--self" && mode === "check") {
      self = true;
    } else {
      throw new InvocationError(`${JSON.stringify(rest[i])} is not an argument ${mode} accepts.`);
    }
  }
  return { mode, root, self };
}

/**
 * Run the script, returning the exit code.
 *
 * @param {string[]} argv
 * @returns {Promise<0 | 1 | 2>}
 */
export async function main(argv) {
  try {
    const { mode, root, self } = parseArgs(argv);
    const tiers = readJson(TIERS_PATH, "the tiers file");
    if (mode === "check" && self) {
      const problems = checkSelf(readJson(CATALOG_PATH, "the committed catalog"), tiers);
      if (problems.length > 0) {
        process.stderr.write(
          `catalog: the committed catalog disagrees with catalog/tiers.json:\n${problems.map((p) => `  ${p}`).join("\n")}\n`,
        );
        return 1;
      }
      process.stdout.write("catalog: OK (the committed catalog matches catalog/tiers.json)\n");
      return 0;
    }
    const generated = generate(root, tiers, buildCatalog);
    if (mode === "write") {
      writeFileSync(CATALOG_PATH, serialize(generated));
      process.stdout.write(
        `catalog: wrote ${CATALOG_PATH} from ${tieredPackages(tiers).length} package.json files under ${root}\n`,
      );
      return 0;
    }
    const differences = diffCatalogs(readJson(CATALOG_PATH, "the committed catalog"), generated);
    if (differences.length > 0) {
      process.stderr.write(
        `catalog: the committed catalog differs from the package.json files under ${root}:\n${differences.map((d) => `  ${d}`).join("\n")}\nRun \`node scripts/catalog.mjs write\` and commit the result.\n`,
      );
      return 1;
    }
    process.stdout.write(
      `catalog: OK (the committed catalog matches the package.json files under ${root})\n`,
    );
    return 0;
  } catch (err) {
    if (err instanceof InvocationError) {
      process.stderr.write(`catalog: ${err.message}\n`);
      return 2;
    }
    throw err;
  }
}

if (isCliEntrypoint(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
